package ru.netology.enumConst;

/**
 * Тип логического блока документа, извлечённого из PDF.
 *
 * <p>Описывает <b>категорию</b> блока (что это — заголовок, абзац, таблица).
 * <b>Не содержит</b> самих данных: текст, уровень заголовка, строки таблицы
 * появятся в отдельном классе {@code Block}, когда начнём писать парсер.
 *
 * <p>Пример: PDF-документ разбивается на последовательность блоков:
 * <pre>
 *   HEADING     "Отчёт за январь"
 *   HEADING     "Транзакции"
 *   PARAGRAPH   "Ниже приведён список операций."
 *   LIST_ITEM   "Покупка в кофейне"
 *   LIST_ITEM   "Возврат в магазине"
 *   TABLE       (строки таблицы)
 *   UNKNOWN     "--- конец документа ---"
 * </pre>
 *
 * <p>Методы (например, {@code isTextual()}, {@code isStructural()})
 * добавляются <b>по мере необходимости</b>, когда появится реальный код,
 * который их вызывает. Сейчас — только константы.
 */
public enum BlockType {

    /**
     * Заголовок.
     * <p>Уровень (1..6, как {@code <h1>}..{@code <h6>} в HTML)
     * хранится <b>отдельно</b> от типа — в будущем классе {@code Block},
     * в поле {@code headingLevel}. Здесь — только «это заголовок».
     */
    HEADING,

    /**
     * Обычный абзац текста.
     */
    PARAGRAPH,

    /**
     * Элемент списка (маркированного или нумерованного).
     */
    LIST_ITEM,

    /**
     * Таблица.
     * <p>Строки (список строк, каждая строка — список ячеек) хранятся
     * <b>отдельно</b> — в будущем классе {@code Block}, в поле
     * {@code tableRows}. Здесь — только «это таблица».
     */
    TABLE,

    /**
     * Не удалось распознать — «сырой» текст сохраняется на всякий случай.
     * <p>Помогает при отладке парсера: видно, что <b>не</b> распознали,
     * и можно дописать правило.
     */
    UNKNOWN
}